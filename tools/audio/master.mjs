// Masters the chosen takes into the game (docs/SOUND_PLAN.md §3):
// public/assets/audio/{fx,music,voice/<lang>}/<id>.m4a and src/data/audioManifest.json.
//
// Which take: effects and music use the owner's `pick` (a cue `replacedBy`
// another uses that one; pick 0 means none); lines use their `pick`, else the
// first take the Scribe check passed, else take 1.
// Loudness (LUFS, peaks ≤ −3 dBTP): effects −16, voices −18, music −23,
// ambience −30 (a quiet bed). AAC in .m4a, which every target browser decodes:
// mono 56 kbps for effects (48 for the ambience), 40 kbps for voices, stereo
// 80 kbps for music. Silence is trimmed from effects and voices (not loops).
//
// Voices are looked up by speaker and the exact text the game shows, so a
// changed text simply has no clip (the bubble still shows) until it is voiced.
//
//   node tools/audio/master.mjs
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { ROOT } from './eleven.mjs';
import { normalize } from './loudness.mjs';

const SRC = resolve(ROOT, 'art/source/audio');
const OUT = resolve(ROOT, 'public/assets/audio');
const cues = JSON.parse(readFileSync(resolve(ROOT, 'audio/cues.json'), 'utf8'));
const gameLines = JSON.parse(readFileSync(resolve(ROOT, 'audio/lines.json'), 'utf8')).lines;
const checks = existsSync(join(SRC, 'checks.json')) ? JSON.parse(readFileSync(join(SRC, 'checks.json'), 'utf8')) : {};
const rec = (dir) => JSON.parse(readFileSync(join(dir, 'cue.json'), 'utf8'));
const duration = (seconds) => Math.round(seconds * 100) / 100;

rmSync(OUT, { recursive: true, force: true });
const manifest = { fx: {}, music: {}, voice: {} };
let bytes = 0;

/** Encode one take; the file name carries a content hash, so caches never keep an old take. */
function encode(input, rel, opts) {
  const tmp = join(OUT, `${rel}.tmp.m4a`);
  mkdirSync(join(tmp, '..'), { recursive: true });
  normalize(input, tmp, { codec: 'aac', ...opts });
  const hash = createHash('sha256').update(readFileSync(tmp)).digest('hex').slice(0, 8);
  const name = rel.replace(/\.m4a$/, `-${hash}.m4a`);
  renameSync(tmp, join(OUT, name));
  bytes += statSync(join(OUT, name)).size;
  return { src: `assets/audio/${name}`, s: duration(measureSeconds(join(OUT, name))) };
}

/** Length in seconds (ffprobe). */
function measureSeconds(file) {
  return Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).toString().trim());
}

const missing = [];

// Effects.
for (const e of cues.effects ?? []) {
  if (e.id.endsWith('-magic')) continue; // alternatives: used through `replacedBy`
  const cue = e.replacedBy ? cues.effects.find((x) => x.id === e.replacedBy) : e;
  if (!cue?.pick) {
    missing.push(`effect ${e.id}`);
    continue;
  }
  const take = rec(join(SRC, 'effects', cue.id)).takes[cue.pick - 1];
  manifest.fx[e.id] = encode(join(SRC, 'effects', cue.id, take.file), `fx/${e.id}.m4a`, { lufs: e.id === 'ambience' ? -30 : -16, mono: true, kbps: e.id === 'ambience' ? 48 : 56, trim: !e.loop });
}

// Music.
for (const m of cues.music ?? []) {
  if (!m.pick) {
    missing.push(`music ${m.id}`);
    continue;
  }
  const take = rec(join(SRC, 'music', m.id)).takes[m.pick - 1];
  manifest.music[m.id] = encode(join(SRC, 'music', m.id, take.file), `music/${m.id}.m4a`, { lufs: -23, kbps: 80 });
}

// Voices.
const model = 'eleven_v4';
for (const l of [...(cues.lines ?? []), ...gameLines]) {
  const dir = join(SRC, 'lines', l.id, model);
  if (!existsSync(join(dir, 'cue.json'))) {
    missing.push(`line ${l.id}`);
    continue;
  }
  const takes = rec(dir).takes;
  const good = takes.findIndex((t) => checks[`${l.id}/${model}/${t.file}`]?.ok);
  const take = takes[(l.pick ?? (good >= 0 ? good + 1 : 1)) - 1];
  const id = l.id.replace(/-(pl|en)$/, '');
  const clip = encode(join(dir, take.file), `voice/${l.lang}/${id}.m4a`, { lufs: -18, mono: true, kbps: 40, trim: true });
  ((manifest.voice[l.lang] ??= {})[l.voice] ??= {})[l.text] = clip;
}

writeFileSync(resolve(ROOT, 'src/data/audioManifest.json'), `${JSON.stringify({ about: 'Generated by tools/audio/master.mjs; do not edit by hand.', ...manifest, bytes }, null, 1)}\n`);
const count = (o) => Object.values(o).reduce((n, v) => n + (v.src ? 1 : count(v)), 0);
console.log(`fx ${count(manifest.fx)}, music ${count(manifest.music)}, voice ${count(manifest.voice)} clips, ${(bytes / 1e6).toFixed(2)} MB`);
if (missing.length) console.log(`not mastered (no pick or no take): ${missing.join(', ')}`);
