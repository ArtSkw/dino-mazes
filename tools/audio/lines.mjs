// Collects every line the game can say aloud from src/data/content.ts and
// src/data/i18n.ts into audio/lines.json (docs/SOUND_PLAN.md §6), so the
// generator voices exactly what the game shows; a changed text gets a new
// hash and is voiced again.
//
//   friends:  hello, little things, cheers, and each quest's first bubble (ask);
//   narrator: quest cards, the first quest, treasure announcements, "Brawo!"
//             and the butterfly hint.
// Lines already in audio/cues.json (the pilot, with the owner's picks) are left
// out here, matched by voice, language and text.
//
//   node tools/audio/lines.mjs
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'rolldown';
import { ROOT } from './eleven.mjs';

const tmp = mkdtempSync(join(tmpdir(), 'dino-lines-'));
const entry = join(tmp, 'entry.ts');
writeFileSync(entry, `export * from ${JSON.stringify(resolve(ROOT, 'src/data/content.ts'))};\nexport { STRINGS } from ${JSON.stringify(resolve(ROOT, 'src/data/i18n.ts'))};\n`);
await build({ input: entry, output: { file: join(tmp, 'data.mjs'), format: 'esm' }, logLevel: 'silent' });
const data = await import(pathToFileURL(join(tmp, 'data.mjs')).href);
rmSync(tmp, { recursive: true, force: true });

const { VOICES, ORDINARY_QUESTS, SPECIAL_QUESTS, GIGANTO_GENERIC, INTRO_PROMPT, TREASURES, TREASURE_AGAIN, ALL_TREASURE_IDS, STRINGS } = data;
const LANGS = ['pl', 'en'];
const cues = JSON.parse(readFileSync(resolve(ROOT, 'audio/cues.json'), 'utf8'));
const voiced = new Set((cues.lines ?? []).map((l) => `${l.voice}|${l.lang}|${l.text}`));
const lines = [];
const add = (id, voice, localized, fill = (s) => s) => {
  for (const lang of LANGS) {
    const text = fill(localized[lang], lang);
    if (!voiced.has(`${voice}|${lang}|${text}`)) lines.push({ id: `${id}-${lang}`, voice, lang, text });
  }
};

for (const [who, v] of Object.entries(VOICES)) {
  add(`${who}-hello`, who, v.hello);
  v.lines.forEach((l, i) => add(`${who}-line${i + 1}`, who, l));
  v.cheers.forEach((l, i) => add(`${who}-cheer${i + 1}`, who, l));
}
for (const q of [...ORDINARY_QUESTS, ...SPECIAL_QUESTS]) {
  add(`ask-${q.id}`, q.characterId, q.ask);
  add(`card-${q.id}`, 'narrator', q.prompt);
}
// Giganto's generic quest asks for any treasure by name.
for (const t of ALL_TREASURE_IDS) add(`ask-giganto-${t}`, 'giganto', GIGANTO_GENERIC.ask, (s, lang) => s.replace('{treasure}', TREASURES[t].name[lang]));
add('card-giganto-treasure', 'narrator', GIGANTO_GENERIC.prompt);
add('card-intro', 'narrator', INTRO_PROMPT);
for (const t of ALL_TREASURE_IDS) {
  const key = TREASURES[t].kind === 'giganto' ? 'newGigantoTreasure' : 'newTreasure';
  add(`new-${t}`, 'narrator', STRINGS[key], (s, lang) => s.replace('{name}', TREASURES[t].name[lang]));
  add(`again-${t}`, 'narrator', TREASURE_AGAIN[t]);
}
add('well-done', 'narrator', STRINGS.wellDone);
add('hint-ready', 'narrator', STRINGS.hintReady);

writeFileSync(resolve(ROOT, 'audio/lines.json'), `${JSON.stringify({ about: 'Generated by tools/audio/lines.mjs from the game texts; do not edit by hand.', lines }, null, 1)}\n`);
const by = lines.reduce((m, l) => ((m[l.voice] = (m[l.voice] ?? 0) + 1), m), {});
console.log(`${lines.length} lines`, by);
