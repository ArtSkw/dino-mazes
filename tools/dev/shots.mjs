import { chromium } from '@playwright/test';
const url = process.argv[2] ?? 'http://localhost:5173/?test';
const out = process.argv[3] ?? '/tmp/dino-shots';
const vw = Number(process.argv[4] ?? 1180), vh = Number(process.argv[5] ?? 820);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: vw, height: vh }, deviceScaleFactor: 2 });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
await page.goto(url);
await page.waitForFunction(() => window.__dino?.ctrl?.state?.screen === 'welcome', null, { timeout: 15000 });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/1-welcome.png` });
await page.getByRole('button', { name: /Graj|Play/ }).click({ force: true });
await page.waitForTimeout(1300);
await page.screenshot({ path: `${out}/2-intro.png` });
await page.getByRole('button', { name: /Szukajmy|Let's look/ }).click({ force: true });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/3-play.png` });
console.log(JSON.stringify(await page.evaluate(() => window.__dino.ctrl.debugInfo())));
console.log(errors.join('\n') || 'no console errors');
await browser.close();
