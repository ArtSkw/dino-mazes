// Dev-only: the living-world details (forced to happen now instead of in 10-60 s).
import { chromium } from '@playwright/test';
const [url = 'http://localhost:5173/?test', out = '/tmp/dino-shots/ambient'] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1180, height: 820 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(url);
await page.waitForFunction(() => window.__dino?.ctrl?.state?.screen === 'welcome', null, { timeout: 30000 });
const force = () => page.evaluate(() => { const g = window.__dino.game.scene.getScene('game'); const a = g.ambient; const n = g.time.now; a.nextLeaf = n; a.nextCloud = n; a.nextGust = n; a.nextTwinkle = n; });
await force();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/1-welcome-leaf.png` });
await page.locator('.cast-btn[data-id="tiny"]').click({ force: true });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/2-greet.png` });
await page.locator('.cast-btn[data-id="giganto"]').click({ force: true });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/3-greet-giganto.png` });
await page.evaluate(() => { const g = window.__dino.game.scene.getScene('game'); g.nextFootsteps = g.time.now; });
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/4-footsteps.png` });
// Play: draw part of the way (sand), then solve (paw prints).
await page.evaluate(() => { const d = window.__dino; d.store.commit({ ...d.store.get(), introDone: true, totalCompleted: 1, activeSession: undefined }); d.store.flush(); });
await page.reload(); await page.waitForFunction(() => window.__dino?.ctrl?.state?.screen === 'welcome');
await page.getByRole('button', { name: /^(Graj|Graj dalej)$/ }).click({ force: true });
await page.getByRole('button', { name: /Szukajmy/ }).click({ force: true });
await page.waitForTimeout(1500);
await force();
const pts = await page.evaluate(() => { const c = window.__dino.ctrl; const m = c.state.maze; const t = c.state.layout.transform; const pos = (id) => id === m.entranceNode ? m.entrance.outside : { x: (id % m.width) + 0.5, y: Math.floor(id / m.width) + 0.5 }; return [m.entranceNode, ...m.metrics.solution].map((n) => { const p = pos(n); return { x: t.ox + p.x * t.pitch, y: t.oy + p.y * t.pitch }; }); });
await page.mouse.move(pts[0].x, pts[0].y); await page.mouse.down();
for (const p of pts.slice(1, 6)) await page.mouse.move(p.x, p.y, { steps: 8 });
await page.screenshot({ path: `${out}/5-sand.png` });
for (const p of pts.slice(6)) await page.mouse.move(p.x, p.y, { steps: 8 });
await page.mouse.up();
await page.waitForFunction(() => window.__dino.ctrl.state.screen === 'reward', null, { timeout: 15000 });
await page.waitForTimeout(2200);
await page.screenshot({ path: `${out}/6-prints.png` });
const flies = await page.evaluate(() => window.__dino.game.scene.getScene('game').ambient.flies.map((f) => f.state));
console.log('flies', flies.join(','), errors.join('\n') || 'no errors');
await browser.close();
